#include "h/pic.h"
#include "h/io.h"
#include "h/types.h"

void pic_remap(){
    outb(0x20,0x11);
    outb(0xA0,0x11);
    outb(0x21,0x20);
    outb(0xA1,0x28);
    outb(0x21,0x04);
    outb(0xA1,0x02);
    outb(0x21,0x01);
    outb(0xA1,0x01);
    outb(0x21,0xFC);
    outb(0xA1,0xFF);
}

void pic_send_eoi(uint32_t irq_number){
    if(irq_number >= 8)outb(0xA0,0x20);
    outb(0x20,0x20);
}